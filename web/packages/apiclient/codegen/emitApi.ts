import { createPlugin } from '@alova/wormhole/plugin'
import type { OpenAPIDocument } from '@alova/wormhole'
import fs from 'node:fs'
import path from 'node:path'

/**
 * Emit the hand-written-shape part of each app's SDK: a positional-argument
 * facade (`api.<group>.<verb>(...)`) over the generated `Apis` proxy, plus the
 * package entry (`index.ts`).
 *
 * wormhole owns `globals.d.ts`, `apiDefinitions.ts` and (through
 * `modelDefaults`) `models.ts`. Everything here runs after the template has
 * rendered, because wormhole's own `index.ts` is only written when the file is
 * missing and cannot be controlled from a template.
 */

/** Stable order for the operations of one path. */
const METHODS = ['get', 'post', 'put', 'delete', 'patch'] as const

const BANNER = `/* eslint-disable */
// AUTO-GENERATED by packages/apiclient from docs/swagger.json — run ./main.sh docs.
`

// Wormhole writes its own per-app `createApis.ts` on every run, and on the next
// run unlinks the file name it recorded. Keeping a forwarding stub there makes
// that unlink hit a real file instead of logging `ENOENT`; nothing imports it.
const STUB_CREATE_APIS = `${BANNER}export { createApis } from '../createApis'\n`

const PREAMBLE = `import { createApis } from '../createApis'
import { $$userConfigMap, alovaInstance } from '../runtime'
import apiDefinitions from './apiDefinitions'
import type { Apis } from './globals'

const $apis = createApis<Apis>(alovaInstance, apiDefinitions, $$userConfigMap)

// The config object a generated proxy method accepts, and the part of it that
// callers may still pass by hand (meta / headers / transform / ...).
type Need<G extends keyof Apis, M extends keyof Apis[G]> = Apis[G][M] extends (...args: any[]) => any
  ? NonNullable<Parameters<Apis[G][M]>[0]>
  : never
type Cfg<G extends keyof Apis, M extends keyof Apis[G]> = Omit<Need<G, M>, 'params' | 'pathParams' | 'data'>
`

// globals.d.ts reads $$userConfigMap / alovaInstance through `typeof`, so both
// stay re-exported here; api.ts re-exports the facade.
const INDEX = `${BANNER}export * from './models'
export { api } from './api'
export { $$userConfigMap, alovaInstance } from '../runtime'
`

const isIdentifier = (name: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)

const lowerFirst = (s: string) => s.replace(/^(\w)/, (_m, c: string) => c.toLowerCase())

type Parameter = { name?: string; in?: string; required?: boolean; schema?: any; type?: string }

/**
 * TypeScript type for one parameter. Only the primitives swag emits are
 * supported; anything else means the swagger doc and this generator disagree,
 * which must fail loudly instead of emitting `any`.
 */
function paramType(param: Parameter, location: string): string {
  const schema = (param.schema ?? {}) as { type?: unknown; enum?: unknown[] }
  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return schema.enum.map((v) => JSON.stringify(v)).join(' | ')
  }
  const type = Array.isArray(schema.type) ? schema.type.find((t) => t !== 'null') : (schema.type ?? param.type)
  switch (type) {
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'string':
    case 'file':
      return 'string'
    default:
      throw new Error(`[emitApi] unsupported type "${String(type)}" for parameter "${param.name}" of ${location}`)
  }
}

/** Renders the lines of one facade method (already indented relative to `group`). */
function methodLines(name: string, args: string[], call: string): string[] {
  const oneLine = `${name}: (${args.join(', ')}) => ${call},`
  if (oneLine.length <= 108) return [`    ${oneLine}`]
  return [`    ${name}: (`, ...args.map((a) => `      ${a},`), `    ) => ${call},`]
}

export const emitApi = createPlugin((outputDir: string, prefixes: string[]) => {
  const outFile = path.join(outputDir, 'api.ts')
  // Rendered while the document is in memory, written only once every other
  // file landed: a failed generation must not leave a half-updated facade.
  let pending: string | null = null

  return {
    afterOpenapiParse(document: OpenAPIDocument) {
      const where = new Map<string, string>() // `Tag.method` -> `METHOD /path`
      const groups = new Map<string, Map<string, string[]>>()

      for (const route of Object.keys(document.paths ?? {}).sort()) {
        if (!prefixes.some((p) => route.startsWith(p))) continue
        const item = document.paths[route] as Record<string, any> | undefined
        for (const method of METHODS) {
          const op = item?.[method]
          if (!op) continue

          const location = `${method.toUpperCase()} ${route}`
          const tag = Array.isArray(op.tags) ? op.tags[0] : undefined
          if (typeof tag !== 'string' || !tag) throw new Error(`[emitApi] ${location} has no tag`)
          if (!isIdentifier(tag)) throw new Error(`[emitApi] ${location} has a non-identifier tag "${tag}"`)
          const name = op.operationId
          if (typeof name !== 'string' || !isIdentifier(name)) {
            throw new Error(`[emitApi] ${location} has a non-identifier operationId "${String(name)}"`)
          }

          const key = `${tag}.${name}`
          const previous = where.get(key)
          if (previous) throw new Error(`[emitApi] "${key}" is emitted twice: ${previous} and ${location}`)
          where.set(key, location)

          const params = (op.parameters ?? []) as Parameter[]
          const pathParams = params.filter((p) => p.in === 'path')
          const queryParams = params.filter((p) => p.in === 'query')
          const hasBody = !!op.requestBody

          const args: string[] = []
          const spread: string[] = []
          for (const p of pathParams) {
            if (typeof p.name !== 'string' || !isIdentifier(p.name)) {
              throw new Error(`[emitApi] ${location} has a non-identifier path parameter "${String(p.name)}"`)
            }
            args.push(`${p.name}: ${paramType(p, location)}`)
          }
          if (pathParams.length > 0) {
            spread.push(`pathParams: { ${pathParams.map((p) => p.name).join(', ')} }`)
          }
          if (hasBody) {
            args.push(`data: Need<'${tag}', '${name}'>['data']`)
            spread.push('data')
          }
          if (queryParams.length > 0) {
            // The generated method requires `params` whenever the endpoint takes
            // query arguments, so the facade does too (pass `{}` for defaults).
            args.push(`params: Need<'${tag}', '${name}'>['params']`)
            spread.push('params')
          }
          args.push(`config?: Cfg<'${tag}', '${name}'>`)

          const call = `$apis.${tag}.${name}({ ...config${spread.map((s) => ', ' + s).join('')} })`
          const group = lowerFirst(tag)
          const methods = groups.get(group) ?? new Map<string, string[]>()
          methods.set(name, methodLines(name, args, call))
          groups.set(group, methods)
        }
      }

      const body = [...groups.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([group, methods]) => {
          const lines = [...methods.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, rendered]) => rendered.join('\n'))
          return `  ${group}: {\n${lines.join('\n')}\n  }`
        })
        .join(',\n')

      pending = `${PREAMBLE}\nexport const api = {\n${body}\n}\n`
    },

    afterCodeGenerate(error?: Error) {
      if (error || !pending) return
      const code = pending
      pending = null

      // Every facade entry must exist in apiDefinitions.ts, otherwise the proxy
      // would throw at call time instead of here.
      const definitionsFile = path.join(outputDir, 'apiDefinitions.ts')
      const definitions = fs.readFileSync(definitionsFile, 'utf8')
      const emitted = new Set([...definitions.matchAll(/'([^']+)': \[/g)].map((m) => m[1]))
      if (emitted.size === 0) throw new Error(`[emitApi] ${definitionsFile} defines no endpoints`)
      for (const [, tag, name] of code.matchAll(/\$apis\.(\w+)\.(\w+)\(/g)) {
        const key = `${tag}.${name}`
        if (!emitted.has(key)) {
          throw new Error(`[emitApi] "${key}" is missing from apiDefinitions.ts`)
        }
      }

      fs.mkdirSync(path.dirname(outFile), { recursive: true })
      fs.writeFileSync(outFile, code)
      // wormhole's proxy type-checks against the global `Apis` that `exposeApis`
      // removed, so it must not survive; the stub keeps its next-run unlink quiet.
      fs.writeFileSync(path.join(outputDir, 'createApis.ts'), STUB_CREATE_APIS)
    },
  }
})

/**
 * Write the package entry. wormhole only creates `index.ts` when it is absent,
 * so neither a template nor `beforeCodeGenerate` can keep it in sync — this
 * runs on every generation instead, and both apps get identical content.
 */
export const emitIndex = createPlugin((outputDir: string) => ({
  afterCodeGenerate(error?: Error) {
    if (error) return
    fs.mkdirSync(outputDir, { recursive: true })
    fs.writeFileSync(path.join(outputDir, 'index.ts'), INDEX)
  },
}))
